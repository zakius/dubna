#!/usr/bin/env python3
"""Moves rust/oganesson_sync to another application-services release.

Usage: tools/update_app_services.py TAG   (for example v159.0)

Pins the tag's commit in Cargo.toml and Cargo.lock, regenerates the places
metrics that glean-build stands in for, and updates the version strings. Then
build each product's Sync library and fix what the new API breaks. Needs git,
cargo and pipx.
"""
import re, subprocess, sys, tempfile, urllib.request
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent / 'rust/oganesson_sync'
REPO = 'https://github.com/mozilla/application-services'
RAW = 'https://raw.githubusercontent.com/mozilla'


def fetch(url):
    with urllib.request.urlopen(url, timeout=30) as response:
        return response.read().decode()


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    tag = sys.argv[1]
    # The peeled commit if the tag is annotated, else the tag's own.
    refs = subprocess.run(['git', 'ls-remote', REPO, f'refs/tags/{tag}', f'refs/tags/{tag}^{{}}'],
                          capture_output=True, text=True, check=True).stdout.split()
    if not refs:
        sys.exit(f'no tag {tag} in {REPO}')
    rev = refs[-2]
    toml, lib = CRATE / 'Cargo.toml', CRATE / 'src/lib.rs'
    old_rev = re.search(r'rev = "([0-9a-f]+)"', toml.read_text())[1]
    old_tag = re.search(r'application-services (v[0-9.]+)', lib.read_text())[1]
    print(f'application-services {old_tag} ({old_rev}) -> {tag} ({rev})')
    toml.write_text(toml.read_text().replace(old_rev, rev))

    # What glean-build would generate: places' metrics.yaml through the
    # glean_parser that places' pinned Glean asks for.
    places = f'{RAW}/application-services/{tag}/components/places'
    glean_tag = re.search(r'^glean-build = .*tag = "([^"]+)"', fetch(f'{places}/Cargo.toml'), re.M)[1]
    parser = re.search(r'^const GLEAN_PARSER_VERSION: &str = "(.*)";',
                       fetch(f'{RAW}/glean/{glean_tag}/glean-core/build/src/lib.rs'), re.M)
    if not parser:
        sys.exit(f"can't find the glean_parser version for Glean {glean_tag}")
    parser = parser[1]
    with tempfile.TemporaryDirectory() as tmp:
        (Path(tmp) / 'metrics.yaml').write_text(fetch(f'{places}/metrics.yaml'))
        subprocess.run(['pipx', 'run', '--spec', f'glean_parser~={parser}', 'glean_parser',
                        'translate', '--output', f'{tmp}/out', '--format', 'rust_sym',
                        f'{tmp}/metrics.yaml'], check=True)
        metrics = (Path(tmp) / 'out/glean_metrics.rs').read_text()
    (CRATE / 'glean-build/src/places_metrics.rs').write_text(
        f'// Pre-generated by glean_parser {parser} (`translate --format rust_sym`) from\n'
        f'// application-services {tag} components/places/metrics.yaml. Regenerate it\n'
        f'// with tools/update_app_services.py. See ../src/lib.rs.\n\n' + metrics)
    glean_toml = CRATE / 'glean-build/Cargo.toml'
    glean_toml.write_text(re.sub(r'(?m)^version = .*', f'version = "{parser}"',
                                 glean_toml.read_text()))
    lib.write_text(lib.read_text().replace(f'application-services {old_tag}',
                                           f'application-services {tag}'))

    # Re-resolves only what the new rev needs; other crates keep their versions.
    subprocess.run(['cargo', 'fetch', '--manifest-path', str(toml)], check=True)
    subprocess.run(['git', '-C', str(CRATE), 'diff', '--stat', '--', '.'], check=True)
    print(f'Upstream changes: {REPO}/compare/{old_rev}...{rev}')


if __name__ == '__main__':
    main()
